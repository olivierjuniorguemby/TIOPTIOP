let pass=0,fail=0; const check=(n,c)=>{console.log(`${c?'✅':'❌'} ${n}`);c?pass++:fail++};
const promo=fs.readFileSync('models/promotion.model.js','utf8');
const loyalty=fs.readFileSync('models/loyalty.model.js','utf8');
const card=fs.readFileSync('models/loyalty-card.model.js','utf8');
const cart=fs.readFileSync('views/client/orders/cart.ejs','utf8');
const checkout=fs.readFileSync('views/client/orders/checkout.ejs','utf8');
check('A — POINTS_MULTIPLIER accepté comme code promo',promo.includes("type === 'POINTS_MULTIPLIER'")&&!promo.includes('bonus de points Tiop+ et non une réduction panier'));
