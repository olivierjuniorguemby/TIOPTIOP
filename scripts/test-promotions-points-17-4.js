check('C — aucune réduction panier pour bonus points',promo.includes("pointsMultiplier: type === 'POINTS_MULTIPLIER' ? value : 1"));
check('D — panier affiche le multiplicateur',cart.includes('Points ×'));
check('E — checkout transporte le multiplicateur',checkout.includes('data-points-multiplier'));
