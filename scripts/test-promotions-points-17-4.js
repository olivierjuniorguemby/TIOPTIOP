check('G — crédit compte Tiop+ relit la promotion serveur',loyalty.includes("p.discount_type='POINTS_MULTIPLIER'"));
check('H — points compte Tiop+ multipliés',loyalty.includes('basePoints * pointsMultiplier'));
check('I — crédit carte physique relit la promotion serveur',card.includes("p.discount_type='POINTS_MULTIPLIER'"));
check('J — points carte physique multipliés',card.includes('basePoints*pointsMultiplier'));
check('K — idempotence EARN compte préservée',loyalty.includes("transaction_type='EARN'"));
check('L — idempotence EARN carte préservée',card.includes("transaction_type='EARN' LIMIT 1"));
console.log(`\nRÉSULTAT 17.4 : PASS=${pass} | FAIL=${fail}`); if(fail)process.exitCode=1; else console.log('✅ 17.4 prête pour validation fonctionnelle.');
